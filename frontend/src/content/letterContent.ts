/**
 * Контент письма — хранится отдельно от визуальных компонентов.
 *
 * Чтобы изменить текст письма, достаточно отредактировать значения
 * этого объекта: компоненты и анимации трогать не нужно.
 * Сейчас используется временный текст-заглушка.
 */
export interface LetterContent {
  /** Заголовок письма. */
  title: string;
  /** Имя получателя (строка «Кому: ...»). */
  recipientName: string;
  /** Абзацы письма — добавляйте/удаляйте элементы массива. */
  paragraphs: string[];
  /** Подпись в конце письма. */
  signature: string;
}

export const letterContent: LetterContent = {
  title: 'Письмо для тебя',
  recipientName: 'Тебе',
  paragraphs: [
    'Здесь будет текст письма.',
    'Этот абзац — временная заглушка. Содержимое задаётся в файле src/content/letterContent.ts и не зависит от оформления интерфейса.',
  ],
  signature: '— с любовью',
};
